const menuToggle = document.querySelector('.menu-toggle');
const nav = document.querySelector('.nav');
const langToggle = document.getElementById('langToggle');
let currentLang = localStorage.getItem('dobe-language') || 'en';

function applyLanguage(lang) {
  currentLang = lang;
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  document.body.classList.toggle('rtl', lang === 'ar');
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const value = translations[lang][el.dataset.i18n];
    if (value !== undefined) el.innerHTML = value;
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const value = translations[lang][el.dataset.i18nPlaceholder];
    if (value !== undefined) el.placeholder = value;
  });
  langToggle.textContent = lang === 'en' ? 'العربية' : 'English';
  langToggle.setAttribute('aria-label', lang === 'en' ? 'Switch to Arabic' : 'Switch to English');
  document.title = lang === 'ar' ? 'DOBE Creative Agency — خلّي براندك يتحرك' : 'DOBE Creative Agency — Make Your Brand Move';
  document.querySelector('meta[name="description"]').content = lang === 'ar'
    ? 'DOBE وكالة تسويق وإبداع تساعد العلامات التجارية على النمو من خلال الاستراتيجية والمحتوى والإعلانات والهوية والمواقع.'
    : 'DOBE Creative Agency helps brands grow through strategy, content, paid advertising, branding, and websites.';
  document.getElementById('service').querySelectorAll('option').forEach((option, index) => {
    if (index > 0) option.value = lang === 'ar' ? option.textContent : [
      '', 'Full marketing support', 'Social media management', 'Content creation & production',
      'Paid advertising', 'Brand identity', 'Website / landing page', "Not sure yet — let's talk"
    ][index];
  });
  const status = document.getElementById('formStatus');
  if (status.dataset.submitted === 'true') status.textContent = translations[lang].formStatus;
  localStorage.setItem('dobe-language', lang);
}
langToggle.addEventListener('click', () => applyLanguage(currentLang === 'en' ? 'ar' : 'en'));

menuToggle?.addEventListener('click', () => {
  const isOpen = nav.classList.toggle('open');
  menuToggle.setAttribute('aria-expanded', String(isOpen));
  menuToggle.textContent = isOpen ? '×' : '☰';
});
nav?.querySelectorAll('a').forEach(link => link.addEventListener('click', () => {
  nav.classList.remove('open');
  menuToggle?.setAttribute('aria-expanded', 'false');
  if (menuToggle) menuToggle.textContent = '☰';
}));
